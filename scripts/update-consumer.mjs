// Versioned release update, deliberately separate from build or deployment.
import {readFileSync,writeFileSync,mkdirSync,existsSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
const [consumerArg,requested='latest',artifactArg]=process.argv.slice(2);
if(!consumerArg||!artifactArg)throw Error('Usage: node scripts/update-consumer.mjs <consumer> <version|latest> <managed-artifact-directory>');
if(requested!=='latest'&&!/^\d+\.\d+\.\d+$/.test(requested))throw Error('Expected a release version or latest');
const consumer=resolve(consumerArg),artifacts=resolve(artifactArg);
if(!existsSync(join(artifacts,'.artifact.json')))throw Error('Use a managed artifact directory');
const repo='onedayonemasterpiece/live-interaction',name='@onedayonemasterpiece/live-interaction';
const response=await fetch(`https://api.github.com/repos/${repo}/releases/${requested==='latest'?'latest':'tags/v'+requested}`,{signal:AbortSignal.timeout(20000)});
if(!response.ok)throw Error(`Release lookup failed: HTTP ${response.status}`);
const release=await response.json(),version=release.tag_name?.replace(/^v/,'');
if(!/^\d+\.\d+\.\d+$/.test(version)||release.draft||release.prerelease)throw Error('Expected a stable versioned release');
const asset=release.assets.find(a=>a.name===`onedayonemasterpiece-live-interaction-${version}.tgz`);
if(!asset||asset.size>5*1024*1024)throw Error('Missing or unexpectedly large release archive');
const download=await fetch(asset.browser_download_url,{signal:AbortSignal.timeout(30000)});if(!download.ok)throw Error(`Release download failed: HTTP ${download.status}`);
const bytes=Buffer.from(await download.arrayBuffer());if(bytes.length!==asset.size)throw Error('Incomplete archive');
const downloaded=join(artifacts,asset.name);writeFileSync(downloaded,bytes);
const packed=JSON.parse(execFileSync('tar',['-xOf',downloaded,'package/package.json'],{encoding:'utf8'}));
if(packed.name!==name||packed.version!==version)throw Error('Archive package identity differs from release');
const sha256=createHash('sha256').update(bytes).digest('hex'),archive=`vendor/live-interaction-${version}.tgz`;
mkdirSync(join(consumer,'vendor'),{recursive:true});writeFileSync(join(consumer,archive),bytes);
const path=join(consumer,'package.json'),manifest=JSON.parse(readFileSync(path));
manifest.dependencies??={};manifest.dependencies[name]='file:'+archive;
manifest.liveFramework={repository:`https://github.com/${repo}`,version,sha256};
writeFileSync(path,JSON.stringify(manifest,null,2)+'\n');
execFileSync('npm',['install','--package-lock-only','--ignore-scripts','--no-audit','--no-fund'],{cwd:consumer,stdio:'inherit'});
console.log(`Live Interaction ${version} selected. Run npm ci, build and consumer acceptance; deployment is a separate step.`);
